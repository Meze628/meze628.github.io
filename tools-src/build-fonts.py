"""Regenerate the small built-in PDF fonts; normal site builds use saved assets."""
import io,json,sys,functools
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools import subset

root=Path(__file__).resolve().parent
assets=root.parent/'static/tools-assets/fonts-pdf'
latin=set()
for start,end in [(0x20,0x250),(0x300,0x530),(0x2000,0x2070),(0x2100,0x2300),(0x3000,0x3040),(0xff00,0xfff0)]:latin.update(range(start,end))
common=set(latin)
for high in range(0xa1,0xf8):
    for low in range(0xa1,0xff):
        try:common.add(ord(bytes([high,low]).decode('gb2312')))
        except UnicodeDecodeError:pass

def ranges(points):
    result=[]
    for point in sorted(points):
        if result and point==result[-1][1]+1:result[-1][1]=point
        else:result.append([point,point])
    return result

def make_font(original,points,family,weight,tier):
    filename=f'{family}-{weight.lower()}-{tier}.woff2'
    if '--reuse' in sys.argv and (assets/filename).exists():return {'file':filename,'bytes':(assets/filename).stat().st_size}
    font=TTFont(io.BytesIO(original),recalcTimestamp=False)
    options=subset.Options()
    options.name_IDs=[0,1,2,3,4,5,6,13,14]
    options.name_legacy=True
    options.notdef_outline=True
    options.desubroutinize=True
    # Horizontal PDF output uses the SC cmap. Omit alternate regional/vertical
    # glyphs while retaining Latin shaping, combining marks and kerning.
    options.layout_features=['kern','liga','clig','ccmp','mark','mkmk','calt']
    worker=subset.Subsetter(options=options)
    worker.populate(unicodes=points)
    worker.subset(font)
    display=f'Meze Tools {family.title()} {tier.title()}'
    postscript=f'MezeTools{family.title()}{weight}{tier.title()}'
    for item in font['name'].names:
        value={1:display,2:weight,3:postscript,4:display+' '+weight,6:postscript,16:display,17:weight}.get(item.nameID)
        if value is not None:item.string=value.encode(item.getEncoding())
    if 'CFF ' in font:
        cff=font['CFF '].cff
        cff.fontNames=[postscript]
        cff.topDictIndex[0].FamilyName=display
        cff.topDictIndex[0].FullName=display+' '+weight
    font.flavor='woff2'
    font.save(assets/filename)
    return {'file':filename,'bytes':(assets/filename).stat().st_size}

@functools.lru_cache(maxsize=4)
def original_bytes(filename):return (assets/filename).read_bytes()

def task(args):
    filename,points,family,weight,tier=args
    result=make_font(original_bytes(filename),set(points),family,weight,tier)
    result['coverage']=ranges(points)
    return result

def main():
    frequent=set(json.loads((root/'data/frequent-han.json').read_text()))
    families={};tasks=[];slots=[]
    for family,prefix in [('sans','NotoSansSC'),('serif','NotoSerifSC')]:
        families[family]={}
        for weight in ['Regular','Bold']:
            filename=f'{prefix}-{weight}.otf';original=original_bytes(filename)
            coverage=set(TTFont(io.BytesIO(original)).getBestCmap())
            face={'shards':[],'full':{'file':filename,'bytes':len(original),'coverage':ranges(coverage)},'coverage':{'latin':ranges(coverage&latin),'common':ranges(coverage&common),'full':ranges(coverage)}}
            families[family][weight.lower()]=face
            for tier,points in [('latin',coverage&latin),('core',coverage&(latin|frequent))]:
                tasks.append((filename,sorted(points),family,weight,tier));slots.append((face,tier))
            points=sorted((coverage&common)-latin)
            for index,start in enumerate(range(0,len(points),32)):
                tasks.append((filename,points[start:start+32],family,weight,f'u{index:03}'));slots.append((face,'shards'))
    with ProcessPoolExecutor(max_workers=4) as pool:
        for index,(slot,result) in enumerate(zip(slots,pool.map(task,tasks))):
            face,tier=slot
            if tier=='shards':face[tier].append(result)
            else:face[tier]=result
            if index%100==0:print(f'Fonts {index+1}/{len(tasks)}',flush=True)
    mono_original=(root/'font-sources/CascadiaMono-Regular.ttf').read_bytes()
    mono_font=TTFont(io.BytesIO(mono_original),recalcTimestamp=False)
    options=subset.Options();options.name_IDs=[0,1,2,3,4,5,6,13,14];options.name_legacy=True
    worker=subset.Subsetter(options=options);worker.populate(unicodes=range(0x20,0x7f));worker.subset(mono_font)
    for item in mono_font['name'].names:
        value={1:'Meze Code',3:'MezeCodeRegular',4:'Meze Code Regular',6:'MezeCodeRegular',16:'Meze Code'}.get(item.nameID)
        if value is not None:item.string=value.encode(item.getEncoding())
    mono_font.save(assets/'code-regular.ttf')
    mono_font.flavor='woff2';mono_font.save(assets/'code-regular.woff2')
    mono={'file':'code-regular.ttf','bytes':(assets/'code-regular.ttf').stat().st_size}
    (root/'src/font-manifest.mjs').write_text('// Generated by build-fonts.py. See fonts-pdf/SUBSET-NOTICE.txt.\nexport const FONT_FAMILIES='+json.dumps(families,separators=(',',':'))+';\nexport const MONO_FONT='+json.dumps(mono,separators=(',',':'))+';\n',encoding='utf-8')
    (assets/'SUBSET-NOTICE.txt').write_text('The sans/serif WOFF2 files are subsets of Noto Sans SC and Noto Serif SC renamed Meze Tools. Code font files are subsets of Cascadia Mono 2407.24 renamed Meze Code. Original outlines, metrics and copyright notices are retained under the corresponding SIL Open Font Licenses in this directory. Core Han characters use the first 1000 characters ranked by the kHanyuPinlu counts in Unicode Unihan 17.0.0; see tools-src/data/README.md and UNICODE-LICENSE.txt. Other supported characters are loaded in shards or from the complete original font. Regenerate with tools-src/build-fonts.py.\n',encoding='utf-8')
    print(json.dumps({'files':len(tasks)+2,'codeBytes':mono['bytes']}),flush=True)

if __name__=='__main__':main()
